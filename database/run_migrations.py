"""
=========================================
CivicPulse Database Migration Runner
=========================================

Applies safe, additive database migrations
to Oracle Database.
"""

import os
import sys

# Add project root to sys.path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from database.connection import get_connection

def run_migrations():
    conn = get_connection()
    if conn is None:
        print("[ERROR] Cannot connect to Oracle DB")
        return False
    
    cur = conn.cursor()
    
    # 1. Add columns to COMPLAINTS if not already present
    print("Checking COMPLAINTS table columns...")
    cur.execute("SELECT column_name FROM user_tab_columns WHERE table_name = 'COMPLAINTS'")
    cols = {r[0] for r in cur.fetchall()}
    
    if 'ASSIGNED_TO' not in cols:
        print("Adding ASSIGNED_TO to COMPLAINTS...")
        try:
            cur.execute("ALTER TABLE COMPLAINTS ADD (ASSIGNED_TO NUMBER)")
            cur.execute("ALTER TABLE COMPLAINTS ADD CONSTRAINT FK_COMPLAINT_WORKER FOREIGN KEY (ASSIGNED_TO) REFERENCES USERS(USER_ID)")
            cur.execute("CREATE INDEX IDX_COMPLAINTS_ASSIGNED ON COMPLAINTS(ASSIGNED_TO)")
            print("[OK] Added ASSIGNED_TO")
        except Exception as e:
            print("[NOTICE] ASSIGNED_TO migration:", e)

    if 'RESOLUTION_PROOF' not in cols:
        print("Adding RESOLUTION_PROOF to COMPLAINTS...")
        try:
            cur.execute("ALTER TABLE COMPLAINTS ADD (RESOLUTION_PROOF VARCHAR2(500))")
            print("[OK] Added RESOLUTION_PROOF")
        except Exception as e:
            print("[NOTICE] RESOLUTION_PROOF migration:", e)

    if 'RESOLVED_AT' not in cols:
        print("Adding RESOLVED_AT to COMPLAINTS...")
        try:
            cur.execute("ALTER TABLE COMPLAINTS ADD (RESOLVED_AT TIMESTAMP)")
            print("[OK] Added RESOLVED_AT")
        except Exception as e:
            print("[NOTICE] RESOLVED_AT migration:", e)

    # 2. Check and create COMPLAINT_IMAGES table
    cur.execute("SELECT table_name FROM user_tables WHERE table_name = 'COMPLAINT_IMAGES'")
    if not cur.fetchone():
        print("Creating COMPLAINT_IMAGES table...")
        try:
            cur.execute("""
                CREATE TABLE COMPLAINT_IMAGES
                (
                    IMAGE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    COMPLAINT_ID NUMBER NOT NULL,
                    IMAGE_PATH VARCHAR2(500) NOT NULL,
                    IMAGE_TYPE VARCHAR2(20) DEFAULT 'COMPLAINT' CHECK (IMAGE_TYPE IN ('COMPLAINT', 'RESOLUTION')),
                    UPLOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT FK_IMAGE_COMPLAINT FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(COMPLAINT_ID)
                )
            """)
            cur.execute("CREATE INDEX IDX_COMPLAINT_IMAGES_COMPLAINT ON COMPLAINT_IMAGES(COMPLAINT_ID)")
            print("[OK] Created COMPLAINT_IMAGES table")
        except Exception as e:
            print("[NOTICE] COMPLAINT_IMAGES creation:", e)
    else:
        print("[INFO] COMPLAINT_IMAGES already exists")

    # 3. Check and create NOTIFICATIONS table
    cur.execute("SELECT table_name FROM user_tables WHERE table_name = 'NOTIFICATIONS'")
    if not cur.fetchone():
        print("Creating NOTIFICATIONS table...")
        try:
            cur.execute("""
                CREATE TABLE NOTIFICATIONS
                (
                    NOTIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    USER_ID NUMBER NOT NULL,
                    COMPLAINT_ID NUMBER,
                    MESSAGE VARCHAR2(500) NOT NULL,
                    IS_READ NUMBER(1) DEFAULT 0,
                    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT FK_NOTIFICATION_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
                    CONSTRAINT FK_NOTIFICATION_COMPLAINT FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(COMPLAINT_ID)
                )
            """)
            cur.execute("CREATE INDEX IDX_NOTIFICATIONS_USER ON NOTIFICATIONS(USER_ID)")
            print("[OK] Created NOTIFICATIONS table")
        except Exception as e:
            print("[NOTICE] NOTIFICATIONS creation:", e)
    else:
        print("[INFO] NOTIFICATIONS already exists")

    # 4. Check and create COMPLAINT_UPVOTES table
    cur.execute("SELECT table_name FROM user_tables WHERE table_name = 'COMPLAINT_UPVOTES'")
    if not cur.fetchone():
        print("Creating COMPLAINT_UPVOTES table...")
        try:
            cur.execute("""
                CREATE TABLE COMPLAINT_UPVOTES
                (
                    UPVOTE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    COMPLAINT_ID NUMBER NOT NULL,
                    USER_ID NUMBER NOT NULL,
                    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT UQ_UPVOTE_USER_COMPLAINT UNIQUE (COMPLAINT_ID, USER_ID),
                    CONSTRAINT FK_UPVOTE_COMPLAINT FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(COMPLAINT_ID),
                    CONSTRAINT FK_UPVOTE_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
                )
            """)
            cur.execute("CREATE INDEX IDX_UPVOTES_COMPLAINT ON COMPLAINT_UPVOTES(COMPLAINT_ID)")
            cur.execute("CREATE INDEX IDX_UPVOTES_USER ON COMPLAINT_UPVOTES(USER_ID)")
            print("[OK] Created COMPLAINT_UPVOTES table")
        except Exception as e:
            print("[NOTICE] COMPLAINT_UPVOTES creation:", e)
    else:
        print("[INFO] COMPLAINT_UPVOTES already exists")

    # 5. Check and create COMPLAINT_FEEDBACK table
    cur.execute("SELECT table_name FROM user_tables WHERE table_name = 'COMPLAINT_FEEDBACK'")
    if not cur.fetchone():
        print("Creating COMPLAINT_FEEDBACK table...")
        try:
            cur.execute("""
                CREATE TABLE COMPLAINT_FEEDBACK
                (
                    FEEDBACK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    COMPLAINT_ID NUMBER NOT NULL,
                    USER_ID NUMBER NOT NULL,
                    RATING NUMBER(1) NOT NULL CHECK (RATING BETWEEN 1 AND 5),
                    COMMENTS VARCHAR2(1000),
                    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT UQ_FEEDBACK_COMPLAINT UNIQUE (COMPLAINT_ID),
                    CONSTRAINT FK_FEEDBACK_COMPLAINT FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(COMPLAINT_ID),
                    CONSTRAINT FK_FEEDBACK_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
                )
            """)
            cur.execute("CREATE INDEX IDX_FEEDBACK_COMPLAINT ON COMPLAINT_FEEDBACK(COMPLAINT_ID)")
            print("[OK] Created COMPLAINT_FEEDBACK table")
        except Exception as e:
            print("[NOTICE] COMPLAINT_FEEDBACK creation:", e)
    else:
        print("[INFO] COMPLAINT_FEEDBACK already exists")

    # 6. Ensure sample Worker users exist for testing Days 15-17
    cur.execute("SELECT COUNT(*) FROM USERS WHERE ROLE = 'Worker'")
    worker_count = cur.fetchone()[0]
    if worker_count == 0:
        print("Adding sample worker accounts...")
        from werkzeug.security import generate_password_hash
        worker_pw = generate_password_hash("worker123")
        try:
            cur.execute("""
                INSERT INTO USERS (FULL_NAME, EMAIL, USER_PASSWORD, PHONE_NUMBER, ROLE)
                VALUES ('Rajesh Kumar', 'worker1@civicpulse.com', :pw, '9876543220', 'Worker')
            """, {"pw": worker_pw})
            cur.execute("""
                INSERT INTO USERS (FULL_NAME, EMAIL, USER_PASSWORD, PHONE_NUMBER, ROLE)
                VALUES ('Priya Sharma', 'worker2@civicpulse.com', :pw, '9876543221', 'Worker')
            """, {"pw": worker_pw})
            print("[OK] Added sample worker accounts (worker1@civicpulse.com / worker123)")
        except Exception as e:
            print("[NOTICE] Worker account creation:", e)

    conn.commit()
    cur.close()
    conn.close()
    print("[SUCCESS] All migrations applied and committed.")
    return True

if __name__ == "__main__":
    run_migrations()
