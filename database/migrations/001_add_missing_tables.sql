-- COMPLAINT_IMAGES table
CREATE TABLE COMPLAINT_IMAGES
(
    IMAGE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPLAINT_ID NUMBER NOT NULL,
    IMAGE_PATH VARCHAR2(500) NOT NULL,
    IMAGE_TYPE VARCHAR2(20) DEFAULT 'COMPLAINT' CHECK (IMAGE_TYPE IN ('COMPLAINT', 'RESOLUTION')),
    UPLOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_IMAGE_COMPLAINT FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(COMPLAINT_ID)
);

CREATE INDEX IDX_COMPLAINT_IMAGES_COMPLAINT ON COMPLAINT_IMAGES(COMPLAINT_ID);

-- STATUS_HISTORY table  
CREATE TABLE STATUS_HISTORY
(
    HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPLAINT_ID NUMBER NOT NULL,
    OLD_STATUS VARCHAR2(20),
    NEW_STATUS VARCHAR2(20) NOT NULL,
    CHANGED_BY NUMBER,
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    REMARKS VARCHAR2(1000),
    CONSTRAINT FK_HISTORY_COMPLAINT FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(COMPLAINT_ID),
    CONSTRAINT FK_HISTORY_USER FOREIGN KEY (CHANGED_BY) REFERENCES USERS(USER_ID)
);

CREATE INDEX IDX_STATUS_HISTORY_COMPLAINT ON STATUS_HISTORY(COMPLAINT_ID);

-- NOTIFICATIONS table
CREATE TABLE NOTIFICATIONS
(
    NOTIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    COMPLAINT_ID NUMBER,
    MESSAGE VARCHAR2(500) NOT NULL,
    IS_READ NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_NOTIFICATION_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_NOTIFICATION_COMPLAINT FOREIGN KEY (COMPLAINT_ID) REFERENCES COMPLAINTS(COMPLAINT_ID)
);

CREATE INDEX IDX_NOTIFICATIONS_USER ON NOTIFICATIONS(USER_ID);

